import * as vscode from "vscode";
import * as path from "path";
import { isExternalLink } from "../vscodeShortcuts";

/**
 * The bundled Draw.io webapp folder, as it appears in VS Code webview resource
 * URLs. Draw.io resolves relative cell links against that folder (see
 * `Graph.getAbsoluteUrl`), so the folder is stripped to recover the relative
 * path the user typed into "Edit Link".
 */
const WEBAPP_MARKER = "/drawio/src/main/webapp/";

export interface DiagramLinkContext {
	/** Document containing the diagram. Relative links resolve next to it. */
	readonly diagramUri: vscode.Uri;
	/** Base URLs Draw.io used to absolutize relative links (offline webapp). */
	readonly baseUrls?: readonly string[];
}

/** Links being opened right now, so rapid repeated clicks open only one tab. */
const pendingLinks = new Set<string>();

/**
 * Whether the URL was generated by VS Code / the local Draw.io server rather
 * than being a real web link. Such URLs must never reach `env.openExternal`:
 * they are relative diagram links that Draw.io absolutized against the webapp
 * folder, and opening them in the browser shows a broken CDN address.
 */
export function isInternalWebviewUrl(href: string): boolean {
	if (!/^[a-z][a-z0-9+.-]*:/i.test(href)) {
		// A raw relative path is handled by the caller, never externally.
		return true;
	}
	// String markers first: webview URLs may contain encoded drive letters or
	// otherwise fail URL parsing, and must still never reach openExternal.
	const markers = [
		"vscode-resource",
		"vscode-webview:",
		"vscode-file:",
		"vscode-cdn.net",
		"127.0.0.1",
		"localhost",
		WEBAPP_MARKER,
		".vscode/extensions",
	];
	if (markers.some((marker) => href.includes(marker))) {
		return true;
	}
	try {
		const url = new URL(href);
		return (
			url.hostname === "127.0.0.1" ||
			url.hostname === "localhost" ||
			url.hostname.includes(".vscode-resource.vscode-cdn.net") ||
			url.protocol === "vscode-webview:" ||
			url.protocol === "vscode-file:" ||
			decodeURIComponent(url.pathname).includes(WEBAPP_MARKER)
		);
	} catch {
		return false;
	}
}

function stripBase(
	href: string,
	baseUrls: readonly string[]
): string | undefined {
	for (const base of baseUrls) {
		if (!base) {
			continue;
		}
		const prefix = base.endsWith("/") ? base : base + "/";
		if (href.startsWith(prefix)) {
			return href.slice(prefix.length);
		}
	}
	return undefined;
}

/**
 * Recovers the relative path the user put into a cell's "Edit Link" field.
 * Draw.io hands the host an absolute URL (a webview resource URL or the local
 * server URL), so both the configured base and the webapp folder marker are
 * checked before falling back to the URL's path.
 */
export function getRelativeLinkPath(
	href: string,
	baseUrls: readonly string[] = []
): string | undefined {
	const trimmed = href.trim();
	if (!trimmed || trimmed.startsWith("#")) {
		return undefined;
	}

	// Some Draw.io click paths (e.g. the "Open Link" menu) keep the raw value.
	if (
		!/^[a-z][a-z0-9+.-]*:/i.test(trimmed) &&
		!trimmed.startsWith("//")
	) {
		return trimmed;
	}

	const fromBase = stripBase(trimmed, baseUrls);
	if (fromBase !== undefined) {
		return fromBase;
	}

	if (!isInternalWebviewUrl(trimmed)) {
		return undefined;
	}

	let url: URL;
	try {
		url = new URL(trimmed);
	} catch {
		return undefined;
	}

	const pathname = decodeURIComponent(url.pathname);
	const marker = pathname.lastIndexOf(WEBAPP_MARKER);
	if (marker >= 0) {
		return pathname.slice(marker + WEBAPP_MARKER.length);
	}
	return pathname.replace(/^\/+/, "");
}

function isInside(root: string, candidate: string): boolean {
	const rel = path.relative(root, candidate);
	return (
		rel === "" ||
		(rel !== ".." &&
			!rel.startsWith(".." + path.sep) &&
			!path.isAbsolute(rel))
	);
}

/** Finds the group of an already open tab showing the file, if any. */
function findOpenColumn(target: vscode.Uri): vscode.ViewColumn | undefined {
	const key = target.toString();
	for (const group of vscode.window.tabGroups.all) {
		for (const tab of group.tabs) {
			const input = tab.input as { uri?: vscode.Uri } | undefined;
			if (input?.uri?.toString() === key) {
				return group.viewColumn;
			}
		}
	}
	const editor = vscode.window.visibleTextEditors.find(
		(item) => item.document.uri.toString() === key
	);
	return editor?.viewColumn;
}

/** Activates an already open file instead of opening a second tab. */
async function activateExisting(
	target: vscode.Uri,
	viewColumn: vscode.ViewColumn
): Promise<void> {
	try {
		const document = await vscode.workspace.openTextDocument(target);
		await vscode.window.showTextDocument(document, { viewColumn });
	} catch {
		// Non-text targets are handled by the editor picker instead.
		await vscode.commands.executeCommand("vscode.open", target, {
			viewColumn,
			preview: false,
		});
	}
}

/**
 * Picks the editor group for the linked file: the group to the right of the
 * diagram's group, else the one to its left, else a new group on the right.
 * Groups are ordered by view column, so gaps in the numbering are harmless.
 */
function resolveTargetColumn(diagramUri: vscode.Uri): vscode.ViewColumn {
	const key = diagramUri.toString();
	const groups = [...vscode.window.tabGroups.all].sort(
		(a, b) => a.viewColumn - b.viewColumn
	);
	const index = groups.findIndex((group) =>
		group.tabs.some((tab) => {
			const input = tab.input as { uri?: vscode.Uri } | undefined;
			return input?.uri?.toString() === key;
		})
	);
	if (index >= 0) {
		if (index + 1 < groups.length) {
			return groups[index + 1].viewColumn;
		}
		if (index - 1 >= 0) {
			return groups[index - 1].viewColumn;
		}
	}
	return vscode.ViewColumn.Beside;
}

/**
 * Handles a link clicked in a diagram: relative paths open in the editor group
 * beside the diagram, web links keep opening in the default browser, and
 * anything else (file:, javascript:, ...) is ignored. Already open files are
 * activated instead of being opened a second time.
 */
export async function handleDiagramLink(
	href: string,
	context: DiagramLinkContext
): Promise<void> {
	const relative = getRelativeLinkPath(href, context.baseUrls ?? []);
	if (relative === undefined) {
		if (isExternalLink(href) && !isInternalWebviewUrl(href)) {
			await vscode.env.openExternal(vscode.Uri.parse(href));
		}
		return;
	}

	// Only relative paths are supported: no query/fragment, no absolute paths
	// and no scheme smuggled in through percent encoding.
	let decoded = relative;
	try {
		decoded = decodeURIComponent(relative);
	} catch {
		// Keep the raw value if it is not valid percent encoding.
	}
	const clean = decoded.split(/[?#]/)[0].replace(/\\/g, "/");
	if (
		!clean ||
		clean.startsWith("/") ||
		/^[a-z][a-z0-9+.-]*:/i.test(clean)
	) {
		return;
	}

	const diagramDir = path.dirname(context.diagramUri.fsPath);
	const targetPath = path.resolve(diagramDir, clean);
	const folder = vscode.workspace.getWorkspaceFolder(context.diagramUri);
	const root = folder ? folder.uri.fsPath : diagramDir;
	if (!isInside(root, targetPath)) {
		vscode.window.showWarningMessage(
			`Draw.io: link points outside the workspace: "${clean}"`
		);
		return;
	}

	const target = vscode.Uri.file(targetPath);
	const key = target.toString();
	if (pendingLinks.has(key)) {
		return;
	}
	const openColumn = findOpenColumn(target);
	pendingLinks.add(key);
	try {
		if (openColumn !== undefined) {
			await activateExisting(target, openColumn);
			return;
		}

		try {
			await vscode.workspace.fs.stat(target);
		} catch {
			vscode.window.showWarningMessage(
				`Draw.io: file not found: "${clean}" (relative to ${diagramDir})`
			);
			return;
		}

		await vscode.commands.executeCommand("vscode.open", target, {
			viewColumn: resolveTargetColumn(context.diagramUri),
			preview: false,
		});
	} finally {
		pendingLinks.delete(key);
	}
}
